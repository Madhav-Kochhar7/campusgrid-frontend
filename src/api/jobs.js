/**
 * Frontend-Only Jobs Service
 * ==========================
 * Manages workload queries, submissions, cancellations, and artifact downloads
 * directly within the frontend application using synchronized local storage.
 */

import { getStoredJobs, addMockJob, deleteMockJob, getMockJob } from './mockData.js'

/**
 * Submits a new job configuration to the local mock orchestrator.
 */
export const submitJob = async (payload) => {
  await new Promise((resolve) => setTimeout(resolve, 300))
  const newJob = addMockJob(payload)
  return {
    job_id: newJob.id,
    ...newJob,
  }
}

/**
 * Retrieves the full list of all active, completed, and queued jobs.
 */
export const getJobs = async () => {
  return Promise.resolve(getStoredJobs())
}

/**
 * Retrieves a single job and its execution state by ID.
 */
export const getJob = async (id) => {
  const job = getMockJob(id)
  if (!job) {
    throw new Error('Workload not found')
  }
  return Promise.resolve(job)
}

/**
 * Retrieves execution console logs for a specific job.
 */
export const getJobLogs = async (id) => {
  const job = getMockJob(id)
  return Promise.resolve(job ? job.logs : [])
}

/**
 * Deletes a job record from the local grid storage.
 */
export const deleteJob = async (id) => {
  await new Promise((resolve) => setTimeout(resolve, 200))
  return Promise.resolve(deleteMockJob(id))
}

/**
 * Generates a real client-side downloadable artifact for the given job.
 */
export const downloadResults = async (id) => {
  const job = getMockJob(id)
  const content = `========================================
CAMPUSGRID WORKLOAD ARTIFACT DOWNLOAD
========================================
Job ID: ${id}
Image: ${job?.image || 'Unknown'}
Status: ${job?.status || 'Done'}
Assigned Node: ${job?.node_id || 'N/A'}
Completed At: ${job?.completed_at || new Date().toISOString()}

----------------------------------------
EXECUTION SPECIFICATIONS
----------------------------------------
CPU Allocation: ${job?.cpu || 4} Core(s)
Memory Allocation: ${job?.memory || '8g'}
GPU Accelerated: ${job?.gpu ? 'Yes' : 'No'}
Total Output Size: 18.4 MB
Process Exit Status: 0 (SUCCESS)

----------------------------------------
COMPUTED DATA ARTIFACTS
----------------------------------------
Output Stream: /campusgrid/storage/${id}/output.bin
Checksum: sha256:${id.replace(/-/g, '')}
Sample Tensor Shape: [1000, 512, 512]
Execution Time: Normal termination.
========================================
Generated by CampusGrid Client Engine.
`
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `results_${id.slice(0, 8)}.txt`
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}
